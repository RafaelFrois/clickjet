// Bitmap pixel fonts drawn with fillRect (no web fonts, crisp at any scale).
//  - FONT_M: 5x7, regular text and numbers
//  - FONT_S: 3x5, small labels and popups
//  - FONT_B: 5x5 chunky block font for titles/buttons (the original's style)
//  - FONT_LOGO: wide 6-row glyphs used only for the CLICKJET logo

function compile(src) {
  const out = {};
  for (const ch in src) {
    const rows = src[ch];
    const h = rows.length, w = rows[0].length;
    const px = [];
    for (let y = 0; y < h; y++) {
      if (rows[y].length !== w) throw new Error(`font glyph '${ch}' row ${y} ragged`);
      for (let x = 0; x < w; x++) if (rows[y][x] === '#') px.push(x, y);
    }
    out[ch] = { w, h, px };
  }
  return out;
}

