function glyphFor(font, ch) {
  const g = font.glyphs[ch];
  if (g) return g;
  const up = font.glyphs[ch.toUpperCase()];
  if (up) return up;
  const low = font.glyphs[ch.toLowerCase()];
  return low || font.glyphs['?'] || null;
}

/** Width in pixels of `text` at integer `scale`. */
export function textWidth(font, text, scale = 1) {
  let w = 0;
  for (let i = 0; i < text.length; i++) {
    const g = glyphFor(font, text[i]);
    if (!g) continue;
    w += g.w + (i < text.length - 1 ? font.spacing : 0);
  }
  return w * scale;
}

/**
 * Draw text. `align`: 'left' | 'center' | 'right'.
 * `color` may be a string or a function (glyphIndex, rowPx) -> color for
 * per-letter / per-row effects (rainbow, gradients).
 * `sx`/`sy` allow non-uniform chunky scaling.
 */
export function drawText(ctx, font, text, x, y, color, opts = {}) {
  const sx = opts.scale || opts.sx || 1;
  const sy = opts.scale || opts.sy || sx;
  const align = opts.align || 'left';
  const w = textWidthXY(font, text, sx);
  let cx = Math.round(align === 'center' ? x - w / 2 : align === 'right' ? x - w : x);
  const cy = Math.round(y);
  const shadow = opts.shadow;
  if (shadow) drawRun(ctx, font, text, cx + (opts.shadowX ?? 0), cy + (opts.shadowY ?? sy), shadow, sx, sy, opts.wave);
  drawRun(ctx, font, text, cx, cy, color, sx, sy, opts.wave);
  return w;
}

function textWidthXY(font, text, sx) {
  return textWidth(font, text, 1) * sx;
}

function drawRun(ctx, font, text, cx, cy, color, sx, sy, wave) {
  const fn = typeof color === 'function';
  if (!fn) ctx.fillStyle = color;
  for (let i = 0; i < text.length; i++) {
    const g = glyphFor(font, text[i]);
    if (!g) continue;
    const oy = wave ? Math.round(wave(i)) : 0;
    const p = g.px;
    for (let k = 0; k < p.length; k += 2) {
      if (fn) ctx.fillStyle = color(i, p[k + 1], g.h);
      ctx.fillRect(cx + p[k] * sx, cy + oy + p[k + 1] * sy, sx, sy);
    }
    cx += (g.w + font.spacing) * sx;
  }
}
